// ---------- Builders ----------
const ACT_COINS = 5;

const mc = (
  question: string,
  opts: Array<[string, boolean]>,
  difficulty: Activity["difficulty"] = "easy",
  instruction = "Escolha a resposta certa"
): Activity => ({
  id: "tmp",
  type: "multiple-choice",
  question,
  instruction,
  options: opts.map(([text, isCorrect], i) => ({ id: `o${i}`, text, isCorrect })),
  coinsReward: ACT_COINS,
  difficulty,
});

const tf = (question: string, answer: boolean): Activity => ({
  id: "tmp",
  type: "true-false",
  question,
  instruction: "Verdadeiro ou Falso",
  options: [
    { id: "true", text: "Verdadeiro", isCorrect: answer },
    { id: "false", text: "Falso", isCorrect: !answer },
  ],
  coinsReward: ACT_COINS,
  difficulty: "easy",
});

const ord = (question: string, items: string[]): Activity => ({
  id: "tmp",
  type: "ordering",
  question,
  instruction: "Coloque na ordem certa",
  options: items.map((text, i) => ({ id: `i${i}`, text })),
  correctOrder: items.map((_, i) => `i${i}`),
  coinsReward: ACT_COINS,
  difficulty: "medium",
});

const mt = (question: string, pairs: Array<[string, string]>): Activity => ({
  id: "tmp",
  type: "matching",
  question,
  instruction: "Conecte os pares",
  options: pairs.flatMap(([left, right], i) => [
    { id: `l${i}`, text: left, matchId: `r${i}` },
    { id: `r${i}`, text: right, matchId: `l${i}` },
  ]),
  coinsReward: ACT_COINS,
  difficulty: "medium",
});

